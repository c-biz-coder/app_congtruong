/**
 * Generate TypeScript types from the local Supabase database
 * (contract section 12).
 *
 * Output: packages/database/src/generated/database.types.ts
 * Requires the `supabase` CLI to be installed and a local DB running.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const TARGET = join(ROOT, 'packages', 'database', 'src', 'generated', 'database.types.ts');

function main(): void {
  try {
    mkdirSync(dirname(TARGET), { recursive: true });
  } catch {
    console.error('❌ db:generate-types: could not create output directory');
    process.exit(1);
  }

  const result = spawnSync('supabase', ['gen', 'types', 'typescript', '--local'], {
    cwd: ROOT,
    encoding: 'utf8',
  });

  if (result.error) {
    console.error('❌ db:generate-types: supabase CLI not found or failed.');
    console.error('   Install it first: https://supabase.com/docs/guides/cli');
    process.exit(1);
  }

  if (result.status !== 0) {
    console.error(result.stderr || '❌ db:generate-types: supabase gen failed');
    process.exit(1);
  }

  writeFileSync(
    TARGET,
    `// Generated by pnpm db:generate-types. Do not edit manually.\n${result.stdout}`,
  );
  console.log(
    `✅ db:generate-types: wrote ${join('packages', 'database', 'src', 'generated', 'database.types.ts')}`,
  );
}

main();
